    private String formatRupiah(int nominal){
        return "RP." + String.format(java.util.Locale.forLanguageTag("id-ID"), "%,d", nominal);
    }
    
    private void hitungTotal(){
    int total = 25000;
    
    if(jGulaAren.isSelected()){
       total += 9000; 
    }
    
    if(jOatmilk.isSelected()){
       total += 20000; 
    }
    
    if(jExtraShot.isSelected()){
       total += 8000; 
    }
    
    jTotalHarga.setText(formatRupiah(total));
    }
